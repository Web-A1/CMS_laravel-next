const INTRODUCTION_PATTERNS = [
  /^Как называются\s+/iu,
  /^(?:Перечислите|Назовите|Заполните|Опишите)\s*,?\s*/iu,
  /^(?:Какие|Какой|Что такое)\s+/iu,
  /^В чём\s+/iu,
  /^Чем образованы\s+/iu,
] as const;

function capitalizeFirstLetter(value: string): string {
  const [firstLetter = "", ...rest] = value;
  return `${firstLetter.toLocaleUpperCase("ru-RU")}${rest.join("")}`;
}

export function assessmentQuestionDisplayPrompt(prompt: string): string {
  return prompt.replace(/\.$/u, "");
}

export function assessmentQuestionNavigationLabel(questionId: string, prompt: string): string {
  const normalizedPrompt = prompt.replace(/\s+/gu, " ").trim();

  if (DIAGRAM_PROMPT_PATTERN.test(normalizedPrompt)) {
    const diagramNumber = /^diagram-(\d+)$/u.exec(questionId)?.[1];
    return diagramNumber === undefined ? "Схема" : `Схема ${Number.parseInt(diagramNumber, 10)}`;
  }

  const compactLabel = COMPACT_LABEL_BY_PROMPT[normalizedPrompt as keyof typeof COMPACT_LABEL_BY_PROMPT];
  if (compactLabel !== undefined) {
    return compactLabel;
  }

  const normalizedGrammar = normalizedPrompt.replace(
    /^Заполните классификацию\s+/iu,
    "Классификация ",
  );
  const withoutIntroduction = INTRODUCTION_PATTERNS.reduce(
    (label, pattern) => label.replace(pattern, ""),
    normalizedGrammar,
  );
  const fallbackLabel = withoutIntroduction
    .replace(/_{3,}/gu, "…")
    .replace(/\s+([,.:;!?])/gu, "$1")
    .replace(/[.?!:]+$/gu, "")
    .replace(/\s+и какого их значение$/iu, " и их значение")
    .trim();

  return capitalizeFirstLetter(fallbackLabel || normalizedPrompt);
}
